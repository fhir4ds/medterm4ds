#!/usr/bin/env python3
"""Generate minimal-pair qualifier tests from the canonical vocabulary.

Two anchors whose token multisets are identical except for ONE token differ
only by that token — resolving a query built from one of them must never
return the other's canonical_id, or the resolver is ignoring the qualifier
(the 'CBC with/without differential' class of wrong answers).

Output: tests/corpora/minimal_pairs.json, consumed by
tests/test_corpora_ner.py (slow-marked).

Usage:
    python3 tests/corpora/tools/generate_ner_minimal_pairs.py \
        [--canonical-dir ~/src/medterm4ds/data/canonical] [--limit 200]
"""

from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

DEFAULT_CANONICAL = Path.home() / "src" / "medterm4ds" / "data" / "canonical"
OUT = Path(__file__).resolve().parents[1] / "tests" / "corpora" / "minimal_pairs.json"

# Qualifier tokens whose swap changes clinical meaning.
POLARITY = {
    "with": "without", "without": "with",
    "positive": "negative", "negative": "positive",
    "left": "right", "right": "left",
    "acute": "chronic", "chronic": "acute",
    "primary": "secondary", "secondary": "primary",
    "malignant": "benign", "benign": "malignant",
    "systolic": "diastolic", "diastolic": "systolic",
    "unilateral": "bilateral", "bilateral": "unilateral",
    "pre": "post", "post": "pre",
    "high": "low", "low": "high",
    "normal": "abnormal", "abnormal": "normal",
}

_TOKEN_RE = re.compile(r"[a-z0-9]+")


def _norm(name: str) -> list[str]:
    return _TOKEN_RE.findall(name.lower())


def load_anchors(canonical_dir: Path) -> list[dict]:
    path = canonical_dir / "canonical_anchor_value_sets.json"
    if not path.is_file():
        return []
    return json.loads(path.read_text())


def find_pairs(anchors: list[dict], limit: int) -> list[dict]:
    """Group anchors by token-multiset minus one token; keep polarity swaps."""
    buckets: dict[tuple[str, ...], list[tuple[str, str, dict]]] = defaultdict(list)
    for anchor in anchors:
        name = anchor.get("patient_friendly_name") or ""
        tokens = _norm(name)
        if len(tokens) < 2 or len(tokens) > 6:
            continue
        for i, token in enumerate(tokens):
            signature = tuple(sorted(tokens[:i] + tokens[i + 1:]))
            buckets[signature].append((token, name, anchor))

    pairs: dict[tuple[str, str], dict] = {}
    for _signature, items in buckets.items():
        if len(items) < 2:
            continue
        for token_a, name_a, anchor_a in items:
            partner = POLARITY.get(token_a)
            if not partner:
                continue
            for token_b, name_b, anchor_b in items:
                if token_b != partner or name_a == name_b:
                    continue
                if anchor_a.get("canonical_id") == anchor_b.get("canonical_id"):
                    continue
                key = tuple(sorted((name_a, name_b)))
                pairs.setdefault(key, {
                    "query_a": name_a, "query_b": name_b,
                    "qualifier_a": token_a, "qualifier_b": token_b,
                    "canonical_a": anchor_a.get("canonical_id"),
                    "canonical_b": anchor_b.get("canonical_id"),
                })
                if len(pairs) >= limit:
                    return sorted(pairs.values(), key=lambda p: p["query_a"])
    return sorted(pairs.values(), key=lambda p: p["query_a"])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--canonical-dir", type=Path, default=DEFAULT_CANONICAL)
    ap.add_argument("--limit", type=int, default=200)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()

    anchors = load_anchors(args.canonical_dir)
    if not anchors:
        raise SystemExit(f"canonical value sets not found in {args.canonical_dir}")
    pairs = find_pairs(anchors, args.limit)
    payload = {
        "_comment": (
            "Generated by tests/corpora/tools/generate_ner_minimal_pairs.py from the shipped "
            "canonical vocabulary. Each pair differs by one polarity token; "
            "resolution must not return the same canonical_id for both."
        ),
        "source": str(args.canonical_dir),
        "pairs": pairs,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(payload, indent=2) + "\n")
    print(f"wrote {len(pairs)} minimal pairs -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
